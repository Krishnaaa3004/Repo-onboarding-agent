import { ActivityFeed } from "./components/ActivityFeed";
import { PlanView } from "./components/PlanView";
import { RepoForm } from "./components/RepoForm";
import { useOnboarding } from "./useOnboarding";

export default function App() {
  const { phase, activity, classification, plan, metrics, error, start } = useOnboarding();
  const running = phase === "running";

  return (
    <div className="page">
      <header className="hero">
        <h1>Repo Onboarding Agent</h1>
        <p>
          Paste a GitHub repo. An agent reads its docs, issues and recent first-time PRs, then gives you a
          checklist: how the code is organised, how to set it up, the house rules, and issues that fit your skills.
        </p>
      </header>

      <RepoForm busy={running} onSubmit={(req) => start(req)} />

      {error && (
        <div className="card error" role="alert">
          <strong>Something went wrong.</strong> {error}
        </div>
      )}

      {running && classification && !plan && (
        <p className="muted center">
          Analysing <strong>{classification.full_name}</strong> ({classification.primary_language}, {classification.size} repo).
          This usually takes under a minute.
        </p>
      )}

      <ActivityFeed items={activity} running={running} />

      {plan && <PlanView plan={plan} metrics={metrics} />}

      <footer className="footer muted small">
        A student project. The plan is generated by an LLM from the repo's own files: double-check commands before running them.
      </footer>
    </div>
  );
}
